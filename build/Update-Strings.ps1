<#
.SYNOPSIS
    Regenerates src/KeeDroidSign/Properties/Strings.cs from Strings.resx.

.DESCRIPTION
    KeePass compiles PLGX sources itself and does not run MSBuild resource generators, so the
    strongly typed accessor is committed as plain C# 5 source. Run this script after editing
    Strings.resx; a test fails if the two files disagree.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$resx = Join-Path $repoRoot 'src/KeeDroidSign/Properties/Strings.resx'
$output = Join-Path $repoRoot 'src/KeeDroidSign/Properties/Strings.cs'

[xml]$doc = Get-Content -LiteralPath $resx -Encoding UTF8
$names = $doc.root.data | ForEach-Object { $_.name } | Sort-Object -CaseSensitive

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// <auto-generated>')
$lines.Add('//   Generated by build/Update-Strings.ps1 from Strings.resx. Do not edit by hand.')
$lines.Add('// </auto-generated>')
$lines.Add('using System.Globalization;')
$lines.Add('using System.Resources;')
$lines.Add('')
$lines.Add('namespace KeeDroidSign.Properties')
$lines.Add('{')
$lines.Add('    /// <summary>User-visible strings (C# 5, so KeePass can compile it as part of the PLGX).</summary>')
$lines.Add('    internal static class Strings')
$lines.Add('    {')
$lines.Add('        private static ResourceManager s_resourceManager;')
$lines.Add('')
$lines.Add('        internal static ResourceManager ResourceManager')
$lines.Add('        {')
$lines.Add('            get')
$lines.Add('            {')
$lines.Add('                if (s_resourceManager == null)')
$lines.Add('                    s_resourceManager = new ResourceManager("KeeDroidSign.Properties.Strings", typeof(Strings).Assembly);')
$lines.Add('                return s_resourceManager;')
$lines.Add('            }')
$lines.Add('        }')
$lines.Add('')
$lines.Add('        internal static CultureInfo Culture { get; set; }')
foreach ($name in $names) {
    $lines.Add('')
    $lines.Add("        internal static string $name")
    $lines.Add('        {')
    $lines.Add("            get { return ResourceManager.GetString(`"$name`", Culture); }")
    $lines.Add('        }')
}
$lines.Add('    }')
$lines.Add('}')

[IO.File]::WriteAllText($output, ($lines -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $($names.Count) strings to $output"
