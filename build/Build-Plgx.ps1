<#
.SYNOPSIS
    Packs the plugin into artifacts/plgx/KeeDroidSign.plgx.

.DESCRIPTION
    KeePass compiles a PLGX from source when it loads it, using the .NET Framework's built-in C#
    compiler (C# 5). This script:
      1. stages the plugin sources, Strings.resx and the prebuilt dependency DLLs
         (KeeDroidSign.Core, BouncyCastle) with a classic .csproj that KeePass's PLGX loader reads;
      2. compiles the staged sources exactly like KeePass does (CSharpCodeProvider, v4.0 compiler),
         so a C# 5 incompatibility fails the build instead of the user's KeePass;
      3. runs "KeePass.exe --plgx-create" to produce the .plgx.

    With -Version X.Y.Z the plugin version in the staged copy of Properties/AssemblyInfo.cs is set to
    X.Y.Z.0 (the source file is not modified) and verified after compilation; the release workflow
    passes the version of the pushed tag.

    Must run in Windows PowerShell 5.1 (powershell.exe), which runs on .NET Framework and therefore
    has the same CodeDom compiler as KeePass. Build the solution in Release and run
    build/Build-KeePassReference.ps1 first.
#>
[CmdletBinding()]
param(
    [string]$Configuration = 'Release',
    [string]$MinKeePassVersion = '2.61',
    [int]$TimeoutSeconds = 180,
    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string]$Version
)

$ErrorActionPreference = 'Stop'

if ($PSVersionTable.PSEdition -eq 'Core') {
    throw 'Run this script with Windows PowerShell 5.1 (powershell.exe): it needs the .NET Framework C# compiler.'
}

$repoRoot = Split-Path -Parent $PSScriptRoot
$pluginDir = Join-Path $repoRoot 'src\KeeDroidSign'
$binDir = Join-Path $pluginDir "bin\$Configuration\net48"
$keePassExe = Join-Path $repoRoot 'artifacts\keepass-ref\KeePass.exe'
$outRoot = Join-Path $repoRoot 'artifacts\plgx'
$stage = Join-Path $outRoot 'KeeDroidSign'
$plgx = Join-Path $outRoot 'KeeDroidSign.plgx'
$libs = @('KeeDroidSign.Core.dll', 'BouncyCastle.Cryptography.dll')
$frameworkRefs = @('System', 'System.Core', 'System.Drawing', 'System.Windows.Forms', 'System.Net.Http', 'System.Xml')

if (-not (Test-Path $keePassExe)) { throw "KeePass reference not found: run build/Build-KeePassReference.ps1 first." }
foreach ($lib in $libs) {
    if (-not (Test-Path (Join-Path $binDir $lib))) { throw "'$lib' not found in '$binDir': build the solution in $Configuration first." }
}

# 1. Stage sources, resources and dependency DLLs.
if (Test-Path $outRoot) { Remove-Item -Recurse -Force $outRoot }
New-Item -ItemType Directory -Force -Path (Join-Path $stage 'lib') | Out-Null

$sources = Get-ChildItem -Path $pluginDir -Recurse -Filter '*.cs' |
    Where-Object { $_.FullName -notmatch '\\(bin|obj)\\' } |
    Sort-Object FullName
$relativeSources = @()
foreach ($file in $sources) {
    $relative = $file.FullName.Substring($pluginDir.Length + 1)
    $target = Join-Path $stage $relative
    New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
    Copy-Item $file.FullName $target
    $relativeSources += $relative
}
Copy-Item (Join-Path $pluginDir 'Properties\Strings.resx') (Join-Path $stage 'Properties\Strings.resx')
foreach ($lib in $libs) { Copy-Item (Join-Path $binDir $lib) (Join-Path $stage "lib\$lib") }

# Stamp the release version into the staged AssemblyInfo.cs only.
if ($Version) {
    $assemblyInfo = Join-Path $stage 'Properties\AssemblyInfo.cs'
    $text = [IO.File]::ReadAllText($assemblyInfo)
    foreach ($attribute in 'AssemblyVersion', 'AssemblyFileVersion') {
        $pattern = '\[assembly: ' + $attribute + '\("[^"]*"\)\]'
        if ($text -notmatch $pattern) { throw "[assembly: $attribute(...)] not found in Properties/AssemblyInfo.cs." }
        $text = [regex]::Replace($text, $pattern, "[assembly: $attribute(""$Version.0"")]")
    }
    [IO.File]::WriteAllText($assemblyInfo, $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Staged plugin version: $Version.0"
}

$xml = New-Object System.Text.StringBuilder
[void]$xml.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$xml.AppendLine('<!-- Generated by build/Build-Plgx.ps1 for KeePass''s PLGX loader. -->')
[void]$xml.AppendLine('<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
[void]$xml.AppendLine('  <PropertyGroup>')
[void]$xml.AppendLine('    <AssemblyName>KeeDroidSign</AssemblyName>')
[void]$xml.AppendLine('    <RootNamespace>KeeDroidSign</RootNamespace>')
[void]$xml.AppendLine('    <TargetFrameworkVersion>v4.8</TargetFrameworkVersion>')
[void]$xml.AppendLine('  </PropertyGroup>')
[void]$xml.AppendLine('  <ItemGroup>')
foreach ($ref in $frameworkRefs) { [void]$xml.AppendLine("    <Reference Include=`"$ref`" />") }
[void]$xml.AppendLine('    <Reference Include="KeePass" />')
foreach ($lib in $libs) {
    $name = [IO.Path]::GetFileNameWithoutExtension($lib)
    [void]$xml.AppendLine("    <Reference Include=`"$name`"><HintPath>lib\$lib</HintPath></Reference>")
}
[void]$xml.AppendLine('  </ItemGroup>')
[void]$xml.AppendLine('  <ItemGroup>')
foreach ($src in $relativeSources) { [void]$xml.AppendLine("    <Compile Include=`"$src`" />") }
[void]$xml.AppendLine('  </ItemGroup>')
[void]$xml.AppendLine('  <ItemGroup>')
[void]$xml.AppendLine('    <EmbeddedResource Include="Properties\Strings.resx" />')
[void]$xml.AppendLine('  </ItemGroup>')
[void]$xml.AppendLine('</Project>')
[IO.File]::WriteAllText((Join-Path $stage 'KeeDroidSign.csproj'), $xml.ToString(), (New-Object System.Text.UTF8Encoding($false)))

# 2. Compile like KeePass: resx -> .resources named <AssemblyName>.<relative path>, CodeDom v4.0 compiler.
Add-Type -AssemblyName System.Windows.Forms
$verifyDir = Join-Path $outRoot 'verify'
New-Item -ItemType Directory -Force -Path $verifyDir | Out-Null
$resources = Join-Path $verifyDir 'KeeDroidSign.Properties.Strings.resources'
$reader = New-Object System.Resources.ResXResourceReader (Join-Path $stage 'Properties\Strings.resx')
$writer = New-Object System.Resources.ResourceWriter $resources
foreach ($entry in $reader) { $writer.AddResource([string]$entry.Key, $entry.Value) }
$writer.Generate(); $writer.Close(); $reader.Close()

$options = New-Object 'System.Collections.Generic.Dictionary[string,string]'
$options.Add('CompilerVersion', 'v4.0')
$provider = New-Object Microsoft.CSharp.CSharpCodeProvider $options
$parameters = New-Object System.CodeDom.Compiler.CompilerParameters
$parameters.OutputAssembly = Join-Path $verifyDir 'KeeDroidSign.dll'
$parameters.GenerateExecutable = $false
$parameters.TreatWarningsAsErrors = $false
foreach ($ref in $frameworkRefs) { [void]$parameters.ReferencedAssemblies.Add("$ref.dll") }
[void]$parameters.ReferencedAssemblies.Add($keePassExe)
foreach ($lib in $libs) { [void]$parameters.ReferencedAssemblies.Add((Join-Path $stage "lib\$lib")) }
[void]$parameters.EmbeddedResources.Add($resources)
$files = $relativeSources | ForEach-Object { Join-Path $stage $_ }
$result = $provider.CompileAssemblyFromFile($parameters, [string[]]$files)
$errors = @($result.Errors | Where-Object { -not $_.IsWarning })
if ($errors.Count -gt 0) {
    $errors | ForEach-Object { Write-Host ("{0}({1}): {2} {3}" -f $_.FileName.Substring($stage.Length + 1), $_.Line, $_.ErrorNumber, $_.ErrorText) }
    throw "The PLGX sources do not compile with KeePass's C# compiler ($($errors.Count) error(s))."
}
Write-Host "Verified: sources compile with the .NET Framework C# compiler used by KeePass."

# KeePass silently skips compiled plugins whose product name is not "KeePass Plugin".
$product = [Diagnostics.FileVersionInfo]::GetVersionInfo($parameters.OutputAssembly).ProductName
if ($product -ne 'KeePass Plugin') {
    throw "The compiled plugin's product name is '$product', so KeePass would ignore it. Set [assembly: AssemblyProduct(""KeePass Plugin"")] in Properties/AssemblyInfo.cs."
}
Write-Host "Verified: product name is 'KeePass Plugin'."

if ($Version) {
    $fileVersion = [Diagnostics.FileVersionInfo]::GetVersionInfo($parameters.OutputAssembly).FileVersion
    if ($fileVersion -ne "$Version.0") {
        throw "The compiled plugin's version is '$fileVersion', expected '$Version.0'."
    }
    Write-Host "Verified: version is $Version.0."
}
Remove-Item -Recurse -Force $verifyDir

# 3. Let KeePass pack the PLGX. Errors open a message box, hence the timeout.
$arguments = @('--plgx-create', "`"$stage`"", "--plgx-prereq-kp:$MinKeePassVersion", '--plgx-prereq-net:4.8')
$process = Start-Process -FilePath $keePassExe -ArgumentList $arguments -PassThru
if (-not $process.WaitForExit($TimeoutSeconds * 1000)) {
    $process.Kill()
    throw "KeePass did not finish creating the PLGX within $TimeoutSeconds s (an error dialog may have been shown)."
}
if (-not (Test-Path $plgx)) { throw "KeePass did not create '$plgx'." }

Remove-Item -Recurse -Force $stage
Write-Host ("OK: {0} ({1} bytes)" -f $plgx, (Get-Item $plgx).Length)
